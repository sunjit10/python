dict1 = {"color": "blue", "age": 30, "isRainy": False}
print(dict1)

print("\nkeys() -  fetch dictionary keys")
print(dict1.keys())

print("\nvalues() -  fetch dictionary values")
print(dict1.values())

print("\nitems() - returns items in dictionary as a list")
dict1_items = dict1.items()
print(dict1_items)
